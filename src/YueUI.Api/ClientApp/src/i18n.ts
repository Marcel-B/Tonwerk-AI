export type MessageKey = keyof (typeof messages)['de']

const storageKey = 'yue-ui.locale'

function initialLocale(): Locale {
  try {
    const stored = localStorage.getItem(storageKey)
    if (stored === 'de' || stored === 'en') {
      return stored
    }
  } catch {
    // Storage may be blocked; fall back to the browser's language.
  }
  return navigator.language.toLowerCase().startsWith('de') ? 'de' : 'en'
}

export const locale = ref<Locale>(initialLocale())

export function setLocale(value: Locale): void {
  locale.value = value
  document.documentElement.lang = value
  try {
    localStorage.setItem(storageKey, value)
  } catch {
    // Remembering the choice is a convenience only.
  }
}

/** A translation for a key built at run time (a model's id, say), or null where there is none. */
export function tMaybe(key: string): string | null {
  return key in messages[locale.value] ? t(key as MessageKey) : null
}

export function t(key: MessageKey, params: Record<string, string | number> = {}): string {
  return messages[locale.value][key].replace(/\{(\w+)\}/g, (_, name: string) => String(params[name] ?? `{${name}}`))
}

/** For keys made at run time, such as a stem's name: whether there is a text for it. */
export function hasMessage(key: string): key is MessageKey {
  return key in messages[locale.value]
}

export function stageLabel(stage: Stage): string {
  return t(`stage_${stage}`)
}

/** The short name of a stage in the song timeline; `stageLabel` says the same in full. */
export function stepLabel(stage: Stage): string {
  return t(`step_${stage}`)
}

/**
 * How far a conversion is, e.g. "45 %". The voice service reports no progress, only an estimate of the whole
 * duration, so the fraction is the time since the start against it; once that has run out, a percentage would
 * stand still at the end, so it says the estimate was exceeded instead.
 */
export function versionProgress(version: Pick<VersionState, 'stage' | 'fraction' | 'estimatedSeconds'>): string {
  if (version.stage !== 'converting' || version.fraction <= 0) {
    return ''
  }
  return version.fraction >= 1
    ? t('versionOverdue', { minutes: Math.max(1, Math.round(version.estimatedSeconds / 60)) })
    : `${Math.min(99, Math.round(version.fraction * 100))} %`
}

export function workerLabel(status: WorkerStatus, busy: boolean): string {
  if (busy) {
    return t('workerBusy')
  }
  return t(status === 'ready' ? 'workerReady' : status === 'starting' ? 'workerStarting' : 'workerStopped')
}

/** An ISO timestamp as the locale writes date and time, e.g. "22.09.2026, 10:05". */
export function formatDateTime(iso: string): string {
  const date = new Date(iso)
  return Number.isNaN(date.getTime())
    ? iso
    : date.toLocaleString(locale.value, { dateStyle: 'short', timeStyle: 'short' })
}

export function formatTime(iso: string): string {
  const date = new Date(iso)
  return Number.isNaN(date.getTime()) ? '' : date.toLocaleTimeString(locale.value, { timeStyle: 'medium' })
}

/** 48_300_000 → "48 MB", 2_150_000_000 → "2.2 GB" (decimal units, as Finder counts). */
export function formatBytes(bytes: number): string {
  const [value, unit] =
    bytes >= 1e9 ? [bytes / 1e9, 'gigabyte'] : bytes >= 1e6 ? [bytes / 1e6, 'megabyte'] : [bytes / 1e3, 'kilobyte']
  return new Intl.NumberFormat(locale.value, {
    style: 'unit',
    unit,
    maximumFractionDigits: value < 10 ? 1 : 0,
  }).format(value)
}

/** 309.4 → "5:09" */
export function formatDuration(seconds: number): string {
  const total = Math.round(seconds)
  return `${Math.floor(total / 60)}:${String(total % 60).padStart(2, '0')}`
}
